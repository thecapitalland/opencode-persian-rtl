const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const { cleanTechnicalText, dominantDirection } = require("../runtime/runtime.js")

assert.equal(
  dominantDirection("OpenCode یک دستیار هوشمند برای برنامه‌نویسی است"),
  "rtl",
)
assert.equal(dominantDirection("OpenCode is a fast coding assistant"), "ltr")
assert.equal(dominantDirection("https://example.com/english/path این یک متن فارسی است"), "rtl")
assert.equal(dominantDirection("C:\\Users\\Name\\project این مسیر درست است"), "rtl")
assert.equal(dominantDirection("test@example.com این ایمیل معتبر است"), "rtl")
assert.equal(dominantDirection("1234 — ..."), null)
assert.equal(dominantDirection("ab اب"), "ltr")
assert.equal(cleanTechnicalText("before https://example.com/a after").trim(), "before   after")

const root = path.resolve(__dirname, "..")
const runtime = fs.readFileSync(path.join(root, "runtime", "runtime.js"), "utf8")
const css = fs.readFileSync(path.join(root, "runtime", "runtime.css"), "utf8")
const installer = fs.readFileSync(path.join(root, "install.ps1"), "utf8")
const uninstaller = fs.readFileSync(path.join(root, "uninstall.ps1"), "utf8")

assert.match(runtime, /MutationObserver/)
assert.match(runtime, /requestAnimationFrame/)
assert.doesNotMatch(runtime, /setInterval/)
assert.match(runtime, /data-component=\\?"markdown/)
assert.match(runtime, /COMPOSER_SELECTOR = '\[data-component=\\?"composer-editor\\?"\]'/)
assert.doesNotMatch(runtime, /prompt-input/)
assert.match(runtime, /home-session-row/)
assert.match(runtime, /titlebar-tab-item/)
assert.match(css, /Vazirmatn\.woff2/)
assert.match(css, /\[data-component="composer-editor"\]\s*\{[^}]*font-family:/s)
assert.doesNotMatch(css, /--font-family-mono\s*:/)
assert.match(installer, /app\.asar/)
assert.match(installer, /opencode-persian-typography:start/)
assert.match(installer, /app\.asar\.backup/)
assert.match(installer, /Assert-RendererContracts/)
assert.match(installer, /composer-editor/)
assert.match(installer, /missing '\$contract'/)
assert.doesNotMatch(installer, /remote-debugging/)
assert.doesNotMatch(installer, /\.Save\(\)/)
assert.match(uninstaller, /originalSha256/)
assert.match(uninstaller, /Refusing to restore a backup from a different build/)

console.log("All runtime checks passed.")